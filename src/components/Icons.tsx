/**
 * Helper to get the canonical line icon for a booth by its number (1-9) or id.
 */
export function getBoothIcon(boothNumberOrId: number | string, size = 22, className = ''): React.ReactElement {
  const num = typeof boothNumberOrId === 'number'
    ? boothNumberOrId
    : parseInt(String(boothNumberOrId).replace(/[^0-9]/g, ''), 10) || 1;

  switch (num) {
    case 1:
      return <ShieldIcon size={size} className={className} />;
    case 2:
      return <BotIcon size={size} className={className} />;
    case 3:
      return <ZapIcon size={size} className={className} />;
    case 4:
      return <CloudIcon size={size} className={className} />;
    case 5:
      return <BrainIcon size={size} className={className} />;
    case 6:
      return <TrendingUpIcon size={size} className={className} />;
    case 7:
      return <LandmarkIcon size={size} className={className} />;
    case 8:
      return <ServerIcon size={size} className={className} />;
    case 9:
      return <RocketIcon size={size} className={className} />;
    default:
      return <GridIcon size={size} className={className} />;
  }
}
